// Static source emitted into every generated fixtures.ts: keeps an auth user's saved session fresh
// (auto re-login), so expired sessions never surface as confusing "element not found" failures.
// Kept as plain lines (no template literals in the emitted code) so it never needs escaping when
// the fixtures generator embeds it.
export const SESSION_HELPERS_SOURCE = [
  "/** A saved session is stale when it's missing, older than the project's sessionMaxAgeMinutes",
  " *  (Settings tab), or any of its cookies has expired (or is about to). */",
  "function sessionIsFresh(statePath: string, maxAgeMinutes: number): boolean {",
  "  if (!existsSync(statePath)) return false;",
  "  if (Date.now() - statSync(statePath).mtimeMs > maxAgeMinutes * 60_000) return false;",
  "  try {",
  "    const state = JSON.parse(readFileSync(statePath, \"utf-8\")) as { cookies?: { expires?: number }[] };",
  "    const soon = Date.now() / 1000 + 60;",
  "    return !(state.cookies ?? []).some((c) => typeof c.expires === \"number\" && c.expires > 0 && c.expires < soon);",
  "  } catch {",
  "    return false;",
  "  }",
  "}",
  "",
  "/** Logs the user in again when their session is stale, writing the new session atomically (temp",
  " *  file + rename) so parallel workers never read a half-written file. Skips the test only when",
  " *  re-login is impossible: no credentials, or no recorded login form. */",
  "async function ensureSession(browser: Browser, testInfo: TestInfo, userId: string, label: string, statePath: string) {",
  "  const maxAge = Number((testInfo.project.metadata as { sessionMaxAgeMinutes?: number } | undefined)?.sessionMaxAgeMinutes ?? 30);",
  "  if (sessionIsFresh(statePath, maxAge)) return;",
  "  const creds = loadCredentialsIfPresent(userId);",
  "  testInfo.skip(!creds, \"User \\\"\" + label + \"\\\" has no credentials file — set a password in the Users tab.\");",
  "  testInfo.skip(!canLogIn, \"User \\\"\" + label + \"\\\" has no fresh session and the map has no recorded login form to renew it — re-run /navmap with creds, or set up the session in the Users tab.\");",
  "  const context = await browser.newContext();",
  "  try {",
  "    const page = await context.newPage();",
  "    await login(page, creds!);",
  "    mkdirSync(dirname(statePath), { recursive: true });",
  "    const tmp = statePath + \".\" + process.pid + \".\" + Date.now() + \".tmp\";",
  "    await context.storageState({ path: tmp });",
  "    try {",
  "      renameSync(tmp, statePath);",
  "    } catch {",
  "      // Another worker won the race and wrote a fresh session meanwhile — use theirs.",
  "      rmSync(tmp, { force: true });",
  "    }",
  "  } finally {",
  "    await context.close();",
  "  }",
  "}",
].join("\n");

// Emitted into every fixtures.ts: reads a number out of an element's text for test cases that
// capture and compare values ("Item total: $29.99" -> 29.99, "$1,234.50" -> 1234.5). Plain lines,
// same reason as above — the regex escapes must reach the generated file untouched.
export const VALUE_HELPERS_SOURCE = [
  "/** The first number in an element's text, ignoring currency symbols and thousands separators. */",
  "export async function readAmount(locator: Locator): Promise<number> {",
  "  const text = (await locator.textContent()) ?? \"\";",
  "  const match = /-?\\d[\\d,]*(?:\\.\\d+)?/.exec(text);",
  "  if (!match) throw new Error(\"No number in \" + JSON.stringify(text));",
  "  return Number(match[0].replace(/,/g, \"\"));",
  "}",
  "",
  "/** An element's visible text, trimmed. */",
  "export async function readText(locator: Locator): Promise<string> {",
  "  return ((await locator.textContent()) ?? \"\").trim();",
  "}",
].join("\n");
